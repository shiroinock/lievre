// Bakes the wear textures and their CSS from wear.config.json: `npm run wear`.
// The tuning page (npm run wear:tune) writes that file; the same values always write the same
// pixels and the same CSS, and src/test/wear.test.tsx fails until they are regenerated.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { deflateSync } from 'node:zlib';
import { normaliseConfig, SHEET_SLICE, TEXT_KINDS, TILE, VARIANTS } from '../src/wear/presets.mjs';
import {
  faceVars,
  sheetThemeVars,
  sheetVars,
  THEMES,
  textures,
  wearVars,
} from '../src/wear/textures.mjs';
import { ageInkVars, ageRules, ageShapeVars, ageTextures } from '../src/wear/age.mjs';

const GUARD = ':not(:has(a, button, input, select, textarea, [tabindex]))';
const block = (selector, declarations) =>
  `  ${selector} {\n${Object.entries(declarations)
    .map(([k, v]) => `    ${k}: ${v};`)
    .join('\n')}\n  }`;
const nth = (n) => (n ? `:nth-of-type(${VARIANTS}n + ${n + 1})` : '');

/**
 * Rules that depend only on the parts (TEXT_KINDS), not on the values: which elements take the
 * dry brush, the live filter and their tile positions. Both modes share them.
 */
export function buildRules() {
  const worn = ".kei:is([data-wear='baked'], [data-wear='live'])";
  const rules = [
    block(`${worn}:not(.kei-portal)`, { 'background-position': 'var(--k-wear-root-pos)' }),
    block(`${worn}:not(.kei-portal)::before`, {
      'border-image': `var(--k-wear-yake) ${SHEET_SLICE} / var(--k-wear-yake-reach) stretch`,
    }),
  ];
  for (let n = 0; n < VARIANTS; n++)
    rules.push(
      block(`${worn} :is(.k-card, .k-metric)${nth(n)}`, {
        'background-position': `var(--k-wear-card-pos-${n})`,
      }),
    );
  for (const [kind, { selectors }] of Object.entries(TEXT_KINDS)) {
    const parts = `:is(${selectors.join(', ')})`;
    rules.push(
      block(`${worn} ${parts}${GUARD}`, {
        'mask-image': `var(--k-wear-${kind}-mask)`,
        'mask-size': `100% 100%, ${TILE}px ${TILE}px`,
        'mask-clip': 'no-clip',
      }),
    );
    for (let n = 0; n < VARIANTS; n++)
      rules.push(
        block(`${worn} ${parts}${nth(n)}${GUARD}`, {
          'mask-position': `0 0, var(--k-wear-${kind}-pos-${n})`,
        }),
        block(`.kei[data-wear='live'] ${parts}${nth(n)}${GUARD}`, {
          filter: `var(--k-wear-${kind}-${n}, none)`,
        }),
      );
    // Baked edges come from the worn faces; baked.css says which kinds take them.
    rules.push(
      block(`.kei[data-wear='baked'] ${parts}${GUARD}`, {
        'font-family': `var(--k-wear-${kind}-face)`,
        '--k-font-mono': `var(--k-wear-${kind}-mono)`,
      }),
    );
  }
  return [
    '/* Generated by scripts/build-wear.mjs from TEXT_KINDS. Do not edit; run npm run wear. */',
    '@layer kei.components {',
    '  @media (not (prefers-contrast: more)) and (not (forced-colors: active)) {',
    ...rules.map((rule) => rule.replace(/^/gm, '  ')),
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Values from the config: the textures, the shared properties and the baked worn faces. */
export function buildWear(config, tokens) {
  const { files: raw, pixels } = textures(config, tokens, (rows) =>
    deflateSync(rows, { level: 9 }),
  );
  const files = Object.fromEntries(Object.entries(raw).map(([k, v]) => [k, Buffer.from(v)]));
  const css = [
    `/* Generated by scripts/build-wear.mjs from wear.config.json (salt "${config.salt}"). Do not edit; run npm run wear. */`,
    '@layer kei.components {',
  ];
  for (const theme of THEMES)
    css.push(
      block(`.kei[data-wear='baked'][data-theme='${theme}']`, {
        '--k-wear-surface': `url('./surface-${theme}.png')`,
        ...sheetThemeVars(
          config,
          theme,
          {
            yake: `url('./yake-${theme}.png')`,
            sure: `url('./sure-${theme}.png')`,
          },
          tokens,
        ),
      }),
    );
  css.push(
    block(".kei[data-wear='baked']", {
      ...wearVars(config, "url('./kasure.png')"),
      ...sheetVars(config),
      ...faceVars(config),
    }),
  );
  css.push('}');

  // Age: the materials per theme and level, and the rules that hand them to the parts.
  const aged = ageTextures(config, tokens, THEMES, (rows) => deflateSync(rows, { level: 9 }));
  for (const [k, v] of Object.entries(aged.files)) files[k] = Buffer.from(v);
  const guard = '  @media (not (prefers-contrast: more)) and (not (forced-colors: active)) {';
  const url = (name) => `url('./${name}')`;
  const age = [
    `/* Generated by scripts/build-wear.mjs from wear.config.json (salt "${config.salt}"). Do not edit; run npm run wear. */`,
    // The faded colours are the theme's own tokens at that age, so they sit with the themes.
    '@layer kei.tokens {',
    guard,
  ];
  for (const level of ['light', 'heavy'])
    for (const theme of THEMES)
      age.push(
        block(
          `.kei[data-age='${level}'][data-theme='${theme}']`,
          ageInkVars(config, tokens, theme, level, url),
        ).replace(/^/gm, '  '),
      );
  age.push('  }', '}', '@layer kei.components {', guard);
  for (const level of ['light', 'heavy'])
    age.push(
      block(`.kei[data-age='${level}']`, ageShapeVars(config, level, url)).replace(/^/gm, '  '),
    );
  age.push(...ageRules().map((rule) => rule.replace(/^/gm, '  ')), '  }', '}');
  pixels.mottle = aged.pixels.mottle;

  const digest = (bytes) => createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const meta = {
    config,
    // Hashes of the pixels before compression, so the check does not depend on the zlib build.
    pixels: Object.fromEntries(Object.entries(pixels).map(([k, v]) => [k, digest(v)])),
    bytes: Object.fromEntries(Object.entries(files).map(([k, v]) => [k, v.length])),
  };
  return {
    files,
    css: css.join('\n') + '\n',
    rules: buildRules(),
    age: age.join('\n') + '\n',
    meta,
  };
}

/** Environment for scripts/wear/font.py: the outline values in 1/1000 em. */
export function outlineEnv(outline) {
  return {
    KEI_WEAR_ROUGH: String(outline.rough),
    KEI_WEAR_ROUGH_SCALE: String(outline.roughScale),
    KEI_WEAR_SWELL: String(outline.swell),
    KEI_WEAR_SWELL_SCALE: String(outline.swellScale),
    KEI_WEAR_STEP: String(outline.step),
  };
}

// Paths are relative to packages/react, where npm runs this package's scripts.
export function readConfig(path = 'wear.config.json') {
  return normaliseConfig(JSON.parse(readFileSync(path, 'utf8')));
}

/** The exchange tokens from @kei-design/tokens, read fresh so an edit shows without a restart. */
export function readTokens() {
  const path = createRequire(import.meta.url).resolve('@kei-design/tokens/tokens.json');
  return JSON.parse(readFileSync(path, 'utf8'));
}

/** Writes src/styles/wear/ for a config. Used by the CLI and by the tuning server on save. */
export function writeWear(config = readConfig()) {
  const tokens = readTokens();
  const out = new URL('../src/styles/wear/', import.meta.url);
  mkdirSync(out, { recursive: true });
  const { files, css, rules, age, meta } = buildWear(config, tokens);
  for (const [name, bytes] of Object.entries(files)) writeFileSync(new URL(name, out), bytes);
  writeFileSync(new URL('baked.css', out), css);
  writeFileSync(new URL('rules.css', out), rules);
  writeFileSync(new URL('age.css', out), age);
  writeFileSync(new URL('wear.json', out), JSON.stringify(meta, null, 2) + '\n');
  return meta;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const meta = writeWear();
  const total = Object.values(meta.bytes).reduce((a, b) => a + b, 0);
  console.log(
    `salt "${meta.config.salt}" (${meta.config.preset}): ${Object.keys(meta.bytes).length} textures, ${(total / 1024).toFixed(1)} KiB`,
  );
}
