// Bakes the wear textures and their CSS from a salt: `npm run wear` (salt "kei"),
// `npm run wear -- --salt=ash`, or KEI_WEAR_SALT=ash npm run wear.
// The same salt always writes the same pixels and the same CSS, so screenshots stay comparable.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { encodeIndexedPng } from './wear/png.mjs';
import { hash32, mulberry32, noise2, seedFor } from '../src/wear/seed.mjs';
import { printMarks } from '../src/wear/marks.mjs';
import {
  KASURE_FLOOR,
  KINDS,
  SURFACE_MAX,
  TEXT_KINDS,
  TILE,
  VARIANTS,
} from '../src/wear/params.mjs';

const LEVELS = 16;
const smooth = (lo, hi, v) => Math.min(1, Math.max(0, (v - lo) / (hi - lo)));

export function resolveSalt(argv = process.argv, env = process.env) {
  const flag = argv.find((a) => a.startsWith('--salt='));
  return flag ? flag.slice(7) : env.KEI_WEAR_SALT || 'kei';
}

/** Grain and stains: opacity 0..1 of the text colour, scaled by SURFACE_MAX later. */
export function surfaceField(salt) {
  const grain = seedFor(salt, 'texture', 'grain');
  const stain = seedFor(salt, 'texture', 'stain');
  const cells = 4; // stain lattice cells per tile, wrapped so the tile repeats seamlessly
  const field = new Float32Array(TILE * TILE);
  for (let y = 0; y < TILE; y++)
    for (let x = 0; x < TILE; x++) {
      const speck = smooth(0.82, 1, hash32(grain, x, y));
      const u = (x / TILE) * cells;
      const v = (y / TILE) * cells;
      const blot =
        noise2(stain, u, v, cells) * 0.65 +
        noise2(stain ^ 0x5bd1e995, u * 2, v * 2, cells * 2) * 0.35;
      field[y * TILE + x] = Math.max(speck, smooth(0.58, 0.82, blot) * 0.7);
    }
  return field;
}

/** Dry brush: 1 where the ink took, dipping to KASURE_FLOOR along short horizontal streaks. */
export function kasureField(salt) {
  const seed = seedFor(salt, 'texture', 'kasure');
  const field = new Float32Array(TILE * TILE);
  for (let y = 0; y < TILE; y++)
    for (let x = 0; x < TILE; x++) {
      const streak =
        noise2(seed, (x / TILE) * 6, (y / TILE) * 64, [6, 64]) * 0.7 + hash32(seed, x, y) * 0.3;
      field[y * TILE + x] = 1 - smooth(0.6, 0.85, streak) * (1 - KASURE_FLOOR);
    }
  return field;
}

// Kasure rounds up so no step falls below KASURE_FLOOR; surfaces stay at or under SURFACE_MAX.
function quantise(field, round = Math.round) {
  const indices = new Uint8Array(field.length);
  for (let i = 0; i < field.length; i++)
    indices[i] = round(Math.min(1, field[i]) * (LEVELS - 1) - 1e-9);
  return indices;
}
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));

/** Per-kind offsets: where each kind's tile starts, and the shift for each repeated variant. */
export function placements(salt) {
  const out = {};
  for (const kind of KINDS) {
    const next = mulberry32(seedFor(salt, kind));
    out[kind] = Array.from({ length: VARIANTS }, () => [
      Math.floor(next() * TILE),
      Math.floor(next() * TILE),
    ]);
  }
  return out;
}

export function buildWear(salt, tokens) {
  const themes = ['paper', 'ink'].map((name) => {
    const set = { ...tokens.paper, ...(name === 'paper' ? {} : tokens[name]) };
    return { name, text: set.text.$value };
  });
  const surface = surfaceField(salt);
  const kasure = kasureField(salt);
  const files = {};
  // Surface alpha tops out at SURFACE_MAX; the palette carries the opacity steps.
  const surfaceIndices = quantise(surface);
  for (const { name, text } of themes) {
    const palette = Array.from({ length: LEVELS }, (_, i) => [
      ...rgb(text),
      Math.round((i / (LEVELS - 1)) * SURFACE_MAX * 255),
    ]);
    files[`surface-${name}.png`] = encodeIndexedPng(TILE, surfaceIndices, palette);
  }
  files['kasure.png'] = encodeIndexedPng(
    TILE,
    quantise(kasure, Math.ceil),
    Array.from({ length: LEVELS }, (_, i) => [0, 0, 0, Math.round((i / (LEVELS - 1)) * 255)]),
  );

  const place = placements(salt);
  const { rule, dash } = printMarks(salt);

  const css = [];
  css.push(
    `/* Generated by scripts/build-wear.mjs from salt "${salt}". Do not edit; run npm run wear. */`,
  );
  css.push('@layer kei.components {');
  for (const { name } of themes)
    css.push(
      `  .kei[data-wear='baked'][data-theme='${name}'] {\n    --k-wear-surface: url('./surface-${name}.png');\n  }`,
    );
  css.push(`  .kei[data-wear='baked'] {
    --k-wear-kasure: url('./kasure.png');
    --k-wear-rule: ${rule};
    --k-wear-dash: ${dash};
  }`);
  // Positions are the "where" in hash(salt + kind + where): the nth repeat of a part.
  const at = ([x, y]) => `${x}px ${y}px`;
  css.push(
    `  .kei[data-wear='baked']:not(.kei-portal) {\n    background-position: ${at(place.root[0])};\n  }`,
  );
  for (let n = 0; n < VARIANTS; n++) {
    css.push(
      `  .kei[data-wear='baked'] :is(.k-card, .k-metric):nth-of-type(${VARIANTS}n + ${n + 1}) {\n    background-position: ${at(place.card[n])};\n  }`,
    );
    for (const [kind, selectors] of Object.entries(TEXT_KINDS))
      css.push(
        `  .kei[data-wear='baked'] :is(${selectors.join(', ')}):nth-of-type(${VARIANTS}n + ${n + 1}) {\n    mask-position: ${at(place[kind][n])};\n  }`,
      );
  }
  css.push('}');

  const digest = (bytes) => createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const meta = {
    salt,
    surfaceMax: SURFACE_MAX,
    kasureFloor: KASURE_FLOOR,
    tile: TILE,
    // Hashes of the pixels before compression, so the check does not depend on the zlib build.
    pixels: { surface: digest(surfaceIndices), kasure: digest(quantise(kasure, Math.ceil)) },
    bytes: Object.fromEntries(Object.entries(files).map(([k, v]) => [k, v.length])),
  };
  return { files, css: css.join('\n') + '\n', meta };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const salt = resolveSalt();
  const tokens = JSON.parse(
    readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'),
  );
  const out = new URL('../src/styles/wear/', import.meta.url);
  mkdirSync(out, { recursive: true });
  const { files, css, meta } = buildWear(salt, tokens);
  for (const [name, bytes] of Object.entries(files)) writeFileSync(new URL(name, out), bytes);
  writeFileSync(new URL('baked.css', out), css);
  writeFileSync(new URL('wear.json', out), JSON.stringify(meta, null, 2) + '\n');
  const total = Object.values(meta.bytes).reduce((a, b) => a + b, 0);
  console.log(
    `salt "${salt}": ${Object.keys(files).length} textures, ${(total / 1024).toFixed(1)} KiB`,
  );
}
