// Bakes the wear textures and their CSS from wear.config.json: `npm run wear`.
// The tuning page (npm run wear:tune) writes that file; the same values always write the same
// pixels and the same CSS, and src/test/wear.test.tsx fails until they are regenerated.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { deflateSync } from 'node:zlib';
import { normaliseConfig, TEXT_KINDS, TILE, VARIANTS } from '../src/wear/presets.mjs';
import { THEMES, textures, wearVars } from '../src/wear/textures.mjs';

const GUARD = ':not(:has(a, button, input, select, textarea, [tabindex]))';
const block = (selector, declarations) =>
  `  ${selector} {\n${Object.entries(declarations)
    .map(([k, v]) => `    ${k}: ${v};`)
    .join('\n')}\n  }`;
const nth = (n) => (n ? `:nth-of-type(${VARIANTS}n + ${n + 1})` : '');

/**
 * Rules that depend only on the parts (TEXT_KINDS), not on the values: which elements take the
 * dry brush, the live filter and their tile positions. Both modes share them.
 */
export function buildRules() {
  const worn = ".kei:is([data-wear='baked'], [data-wear='live'])";
  const rules = [
    block(`${worn}:not(.kei-portal)`, { 'background-position': 'var(--k-wear-root-pos)' }),
  ];
  for (let n = 0; n < VARIANTS; n++)
    rules.push(
      block(`${worn} :is(.k-card, .k-metric)${nth(n)}`, {
        'background-position': `var(--k-wear-card-pos-${n})`,
      }),
    );
  for (const [kind, { selectors }] of Object.entries(TEXT_KINDS)) {
    const parts = `:is(${selectors.join(', ')})`;
    rules.push(
      block(`${worn} ${parts}${GUARD}`, {
        'mask-image': `var(--k-wear-${kind}-mask)`,
        'mask-size': `100% 100%, ${TILE}px ${TILE}px`,
        'mask-clip': 'no-clip',
      }),
    );
    for (let n = 0; n < VARIANTS; n++)
      rules.push(
        block(`${worn} ${parts}${nth(n)}${GUARD}`, {
          'mask-position': `0 0, var(--k-wear-${kind}-pos-${n})`,
        }),
        block(`.kei[data-wear='live'] ${parts}${nth(n)}${GUARD}`, {
          filter: `var(--k-wear-${kind}-${n}, none)`,
        }),
      );
  }
  return [
    '/* Generated by scripts/build-wear.mjs from TEXT_KINDS. Do not edit; run npm run wear. */',
    '@layer kei.components {',
    '  @media (not (prefers-contrast: more)) and (not (forced-colors: active)) {',
    ...rules.map((rule) => rule.replace(/^/gm, '  ')),
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Values from the config: the textures, the shared properties and the baked worn faces. */
export function buildWear(config, tokens) {
  const { files: raw, pixels } = textures(config, tokens, (rows) =>
    deflateSync(rows, { level: 9 }),
  );
  const files = Object.fromEntries(Object.entries(raw).map(([k, v]) => [k, Buffer.from(v)]));
  const css = [
    `/* Generated by scripts/build-wear.mjs from wear.config.json (salt "${config.salt}"). Do not edit; run npm run wear. */`,
    '@layer kei.components {',
  ];
  for (const theme of THEMES)
    css.push(
      block(`.kei[data-wear='baked'][data-theme='${theme}']`, {
        '--k-wear-surface': `url('./surface-${theme}.png')`,
      }),
    );
  css.push(block(".kei[data-wear='baked']", wearVars(config, "url('./kasure.png')")));
  // Distorted kinds take the worn faces from `npm run wear:font`; others keep the plain ones.
  for (const [kind, { selectors, font }] of Object.entries(TEXT_KINDS))
    if (config.kinds[kind].distort)
      css.push(
        block(`.kei[data-wear='baked'] :is(${selectors.join(', ')})${GUARD}`, {
          'font-family': `var(--k-wear-${font})`,
          '--k-font-mono': 'var(--k-wear-mono)',
        }),
      );
  css.push('}');

  const digest = (bytes) => createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const meta = {
    config,
    // Hashes of the pixels before compression, so the check does not depend on the zlib build.
    pixels: { surface: digest(pixels.surface), kasure: digest(pixels.kasure) },
    bytes: Object.fromEntries(Object.entries(files).map(([k, v]) => [k, v.length])),
  };
  return { files, css: css.join('\n') + '\n', rules: buildRules(), meta };
}

// Paths are relative to the repository root, where npm runs scripts.
export function readConfig(path = 'wear.config.json') {
  return normaliseConfig(JSON.parse(readFileSync(path, 'utf8')));
}

/** Writes src/styles/wear/ for a config. Used by the CLI and by the tuning server on save. */
export function writeWear(config = readConfig()) {
  const tokens = JSON.parse(
    readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'),
  );
  const out = new URL('../src/styles/wear/', import.meta.url);
  mkdirSync(out, { recursive: true });
  const { files, css, rules, meta } = buildWear(config, tokens);
  for (const [name, bytes] of Object.entries(files)) writeFileSync(new URL(name, out), bytes);
  writeFileSync(new URL('baked.css', out), css);
  writeFileSync(new URL('rules.css', out), rules);
  writeFileSync(new URL('wear.json', out), JSON.stringify(meta, null, 2) + '\n');
  return meta;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const meta = writeWear();
  const total = Object.values(meta.bytes).reduce((a, b) => a + b, 0);
  console.log(
    `salt "${meta.config.salt}" (${meta.config.preset}): ${Object.keys(meta.bytes).length} textures, ${(total / 1024).toFixed(1)} KiB`,
  );
}
